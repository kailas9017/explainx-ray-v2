def generate_finding_explanation(finding: dict) -> str:
    """Build a factual explanation using only the computed finding fields."""
    name = finding["name"]
    prob_pct = round(finding["probability"] * 100)
    zone = finding["primaryZone"]
    pattern = finding["distribution"]["pattern"].lower()
    af_pct = round(finding["asfi"]["activatedFraction"] * 100)
    asfi = finding["asfi"]["score"]
    severity = finding["severity"]

    pattern_phrase = {
        "focal": f"tightly localized to the {zone} region",
        "multifocal": f"present across several zones, most prominently {zone}",
        "diffuse": "distributed broadly across the lung fields rather than one specific zone",
    }[pattern]

    return (
        f"The model assigned {name} a probability of {prob_pct}%, based on "
        f"Grad-CAM activation covering {af_pct}% of the lung field, {pattern_phrase}. "
        f"This activation pattern was classified as {pattern} "
        f"(zone concentration index {finding['distribution']['zci']}). "
        f"Combining activation extent, intensity, and model confidence gives an "
        f"ASFI severity score of {asfi}/100, placing this finding in the "
        f"'{severity}' category."
    )


def generate_clinical_report(findings: list, model_info: dict) -> dict:
    per_finding = [{"name": finding["name"], "explanation": generate_finding_explanation(finding)}
                   for finding in findings]

    if not findings:
        summary = "No findings met the model's reporting threshold for this scan."
    else:
        top = findings[0]
        summary = (
            f"Primary finding: {top['name']} ({round(top['probability'] * 100)}% probability, "
            f"{top['severity']} severity)."
        )
        if len(findings) > 1:
            summary += f" {len(findings) - 1} additional finding(s) also met threshold."

    return {
        "summary": summary,
        "findings": per_finding,
        "methodology": (
            f"Findings generated by a {model_info.get('numClasses', '?')}-class DenseNet121 "
            "classifier, transfer-learned on NIH ChestX-ray14. Explanations are derived from "
            "Grad-CAM activation over the model's final convolutional block, thresholded "
            "per-image using Otsu's method. Zone-wise localization divides the image into a "
            "6-region grid (Right/Left × Upper/Mid/Lower)."
        ),
        "disclaimer": (
            "This report is generated by an automated model for academic/demonstration "
            "purposes and has not been reviewed by a radiologist. It is not a diagnosis."
        ),
    }
